// ─── Confidence Numeric Mapping ───────────────────────────────

export const CONFIDENCE_SCORES: Record<TrustConfidence, number> = {
  high: 90,
  medium: 65,
  low: 35,
};

// ─── TRUST Score Computation ────────────────────────────────────

/**
 * Compute a TRUST score from metadata.
 *
 * @param metadata - The TRUST metadata to score
 * @param options - Optional overrides (e.g., custom freshness baseline)
 * @returns TrustScore with composite score and dimensional breakdown
 */
export function computeTrustScore(
  metadata: TrustMetadata,
  options?: { now?: Date; maxAgeDays?: number }
): TrustScore {
  const now = options?.now || new Date();
  const maxAgeDays = options?.maxAgeDays || 90;

  // Source reliability (0-100)
  const sourceScore = SOURCE_RELIABILITY_SCORES[metadata.source];

  // Confidence level (0-100)
  const confidenceScore = CONFIDENCE_SCORES[metadata.confidence];

  // Freshness score (0-100) — decays over time
  const freshnessDate = new Date(metadata.freshness);
  const ageDays = Math.max(0, (now.getTime() - freshnessDate.getTime()) / (1000 * 60 * 60 * 24));
  const freshnessDecay = Math.max(0, 1 - (ageDays / maxAgeDays));
  const freshnessScore = Math.round(freshnessDecay * 100);

  // Evidence count score (0-100)
  const evidenceCount = metadata.evidenceCount || 1;
  const evidenceScore = Math.min(100, Math.round(50 + (evidenceCount * 10)));

  // Weighted composite
  const composite = Math.round(
    (sourceScore * 0.30) +
    (confidenceScore * 0.25) +
    (freshnessScore * 0.25) +
    (evidenceScore * 0.20)
  );

  return {
    score: composite,
    grade: scoreToGrade(composite),
    dimensions: {
      source: sourceScore,
      confidence: confidenceScore,
      freshness: freshnessScore,
      evidence: evidenceScore,
    },
    metadata,
  };
}

function scoreToGrade(score: number): TrustScore['grade'] {
  if (score >= 95) return 'A+';
  if (score >= 85) return 'A';
  if (score >= 70) return 'B';
  if (score >= 55) return 'C';
  if (score >= 40) return 'D';
  return 'F';
}

