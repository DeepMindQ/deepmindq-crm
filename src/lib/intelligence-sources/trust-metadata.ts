/**
 * Create TRUST metadata for verified API data.
 */
export function verifiedApiTrust(
  field: string,
  provider: string,
  originalValue: string,
  reasoning?: string
): TrustMetadata {
  return {
    source: 'verified_api',
    confidence: 'high',
    freshness: new Date().toISOString(),
    reasoning: reasoning || `Field "${field}" directly verified by ${provider} API.`,
    provider,
    field,
    originalValue,
    verificationStatus: 'verified',
  };
}

/**
 * Create TRUST metadata for customer-provided data.
 */
export function customerDataTrust(
  field: string,
  originalValue: string,
  reasoning?: string
): TrustMetadata {
  return {
    source: 'customer_data',
    confidence: 'high',
    freshness: new Date().toISOString(),
    reasoning: reasoning || `Field "${field}" provided directly by customer.`,
    field,
    originalValue,
    verificationStatus: 'verified',
  };
}

/**
 * Create TRUST metadata for AI-generated intelligence.
 * Always starts at 'low' or 'medium' — must earn higher confidence.
 */
export function aiInferenceTrust(
  field: string,
  reasoning: string,
  evidenceCount: number = 0,
  confidence: TrustConfidence = 'low'
): TrustMetadata {
  return {
    source: 'ai_inference',
    confidence,
    freshness: new Date().toISOString(),
    reasoning,
    field,
    evidenceCount,
    verificationStatus: evidenceCount >= 2 ? 'cross_referenced' : 'inferred',
  };
}

