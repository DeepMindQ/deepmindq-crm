/**
 * M5 Phase 1.5 — TRUST Metadata Framework
 *
 * Universal standard for every intelligence output in DeepMindQ.
 * Every data point, signal, recommendation, and insight must carry
 * TRUST metadata so enterprise buyers can evaluate credibility.
 *
 * TRUST = Transparency, Reliability, Understandability, Source, Traceability
 *
 * Four mandatory dimensions:
 *   1. Source    — Where did this intelligence come from?
 *   2. Confidence — How reliable is this assessment?
 *   3. Freshness  — When was this last verified?
 *   4. Reasoning  — Why did the system reach this conclusion?
 *
 * Source Classification:
 *   verified_api     — Directly from a verified external API (Clearbit, Apollo)
 *   customer_data    — Entered by the customer (CRM data, uploads)
 *   internal_document — From ingested documents (knowledge base)
 *   web_intelligence  — From web search/intelligence collection
 *   ai_inference      — Generated by AI reasoning (lowest default trust)
 *   platform_computed — Computed by platform engines (scoring, matching)
 *
 * Confidence Levels:
 *   high   — Verified from multiple sources or direct provider data
 *   medium — Estimated from signals or single-source data
 *   low    — Inferred or AI-generated without strong evidence
 *
 * Design Principles:
 *   - NEVER present AI-estimated data as verified fact
 *   - Every output must be auditable back to its source
 *   - Confidence degradation over time (freshness decay)
 *   - Composable: trust scores aggregate upward
 */

// ─── Core Types ────────────────────────────────────────────────

/** Where intelligence originated */
export type TrustSource =
  | 'verified_api'
  | 'customer_data'
  | 'internal_document'
  | 'web_intelligence'
  | 'ai_inference'
  | 'platform_computed';

/** Reliability level of the intelligence */
export type TrustConfidence = 'high' | 'medium' | 'low';

/** Verification status of the data point */
export type TrustVerificationStatus =
  | 'verified'        // Confirmed by external source
  | 'cross_referenced' // Corroborated by 2+ sources
  | 'estimated'       // Platform estimation
  | 'inferred'        // AI inference
  | 'unverified';     // No verification performed

// ─── TRUST Metadata ────────────────────────────────────────────

/**
 * The core TRUST metadata object.
 * Attached to every intelligence output in the platform.
 */
export interface TrustMetadata {
  /** Where this intelligence originated */
  source: TrustSource;

  /** Confidence level: high / medium / low */
  confidence: TrustConfidence;

  /** ISO 8601 timestamp of last verification */
  freshness: string;

  /** Human-readable explanation of why this conclusion was reached */
  reasoning: string;

  /** Optional: Specific data provider (e.g., 'clearbit', 'apollo', 'tavily') */
  provider?: string;

  /** Optional: Specific field this metadata applies to */
  field?: string;

  /** Optional: Original raw value before platform processing */
  originalValue?: string;

  /** Optional: Number of evidence sources backing this assessment */
  evidenceCount?: number;

  /** Optional: Verification status */
  verificationStatus?: TrustVerificationStatus;
}

// ─── TRUST Score ───────────────────────────────────────────────

/**
 * Aggregated TRUST score (0-100) computed from metadata dimensions.
 * Used for quick sorting, filtering, and display.
 *
 * Weighting:
 *   Source reliability:    30%
 *   Confidence level:      25%
 *   Freshness recency:    25%
 *   Evidence count:       20%
 */
export interface TrustScore {
  /** Composite score 0-100 */
  score: number;

  /** Letter grade for quick visual scanning */
  grade: 'A+' | 'A' | 'B' | 'C' | 'D' | 'F';

  /** Breakdown by dimension */
  dimensions: {
    source: number;      // 0-100
    confidence: number;  // 0-100
    freshness: number;    // 0-100
    evidence: number;    // 0-100
  };

  /** The metadata this score was computed from */
  metadata: TrustMetadata;
}

// ─── Source Reliability Scores ─────────────────────────────────

/**
 * Static reliability scores for each source type.
 * These are NOT ML-derived — they are deterministic based on source characteristics.
 */
export const SOURCE_RELIABILITY_SCORES: Record<TrustSource, number> = {
  verified_api: 95,
  customer_data: 90,
  internal_document: 85,
  web_intelligence: 70,
  platform_computed: 80,
  ai_inference: 55,
};

// ─── Consolidated Reliability Score ──────────────────────────────

/** Mapping from legacy SourceType strings to their equivalent TrustSource */
const SOURCE_TYPE_TO_TRUST_SOURCE: Record<string, TrustSource> = {
  clearbit: 'verified_api',
  apollo: 'verified_api',
  crunchbase: 'verified_api',
  csv: 'customer_data',
  excel: 'customer_data',
  document: 'internal_document',
  human: 'customer_data',
  website: 'web_intelligence',
  rss: 'web_intelligence',
};

/**
 * Get the reliability score (0-100) for a given source.
 *
 * This is the SINGLE SOURCE OF TRUTH for source reliability.
 * Accepts either a TrustSource or a legacy SourceType string.
 *
 * @param source - A TrustSource (e.g., 'verified_api') or SourceType (e.g., 'clearbit')
 * @returns Reliability score 0-100
 */
export function getReliabilityScore(source: string): number {
  // If it's a direct TrustSource, look it up
  if (source in SOURCE_RELIABILITY_SCORES) {
    return SOURCE_RELIABILITY_SCORES[source as TrustSource];
  }
  // Otherwise, map from legacy SourceType to TrustSource
  const mappedTrustSource = SOURCE_TYPE_TO_TRUST_SOURCE[source];
  if (mappedTrustSource) {
    return SOURCE_RELIABILITY_SCORES[mappedTrustSource];
  }
  // Unknown source — return lowest default
  return 55;
}

