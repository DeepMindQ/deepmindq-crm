// ─── TRUST Aggregation ─────────────────────────────────────────

/**
 * Aggregate multiple TRUST metadata objects into a single composite.
 * Used when composing intelligence from multiple sources (e.g., WOW #1).
 *
 * Strategy: Weighted average with confidence boost for cross-referencing.
 */
export function aggregateTrust(trustItems: TrustMetadata[]): TrustMetadata {
  if (trustItems.length === 0) {
    return {
      source: 'ai_inference',
      confidence: 'low',
      freshness: new Date().toISOString(),
      reasoning: 'No trust metadata available.',
    };
  }

  if (trustItems.length === 1) {
    return trustItems[0]!;
  }

  // Count sources by type
  const sourceCounts = new Map<TrustSource, number>();
  let totalEvidence = 0;
  let newestDate = '';

  for (const item of trustItems) {
    sourceCounts.set(item.source, (sourceCounts.get(item.source) || 0) + 1);
    totalEvidence += item.evidenceCount || 1;
    if (item.freshness > newestDate) {
      newestDate = item.freshness;
    }
  }

  // Determine composite confidence
  const hasVerifiedApi = sourceCounts.has('verified_api');
  const hasCustomerData = sourceCounts.has('customer_data');
  const hasMultipleSources = sourceCounts.size >= 2;

  let compositeConfidence: TrustConfidence = 'low';
  if (hasVerifiedApi && hasCustomerData && hasMultipleSources) {
    compositeConfidence = 'high';
  } else if (hasVerifiedApi || hasCustomerData || hasMultipleSources) {
    compositeConfidence = 'medium';
  }

  // Determine primary source (highest reliability)
  const sourcePriority: TrustSource[] = [
    'verified_api', 'customer_data', 'internal_document',
    'platform_computed', 'web_intelligence', 'ai_inference',
  ];
  let primarySource: TrustSource = 'ai_inference';
  for (const s of sourcePriority) {
    if (sourceCounts.has(s)) {
      primarySource = s;
      break;
    }
  }

  return {
    source: primarySource,
    confidence: compositeConfidence,
    freshness: newestDate || new Date().toISOString(),
    reasoning: `Composite intelligence from ${trustItems.length} sources: ${Array.from(sourceCounts.entries()).map(([s, c]) => `${s}(${c})`).join(', ')}.`,
    evidenceCount: totalEvidence,
    verificationStatus: hasMultipleSources ? 'cross_referenced' : 'estimated',
  };
}

// ─── TRUST Decorator ────────────────────────────────────────────

/**
 * Wrap any data object with TRUST metadata.
 * Returns the original object with an added `_trust` field.
 *
 * Usage:
 *   const enriched = withTrust(companyData, verifiedApiTrust('employees', 'clearbit', '15420'));
 */
export function withTrust<T>(data: T, trust: TrustMetadata): T & { _trust: TrustMetadata } {
  return {
    ...data,
    _trust: trust,
  };
}

/**
 * Wrap an array of data items with their corresponding TRUST metadata.
 */
export function withTrustBatch<T>(
  items: T[],
  trusts: TrustMetadata[]
): (T & { _trust: TrustMetadata })[] {
  return items.map((item, i) => ({
    ...item,
    _trust: trusts[i] || {
      source: 'ai_inference',
      confidence: 'low',
      freshness: new Date().toISOString(),
      reasoning: 'No trust metadata available for this item.',
    },
  }));
}
